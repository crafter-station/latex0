#!/usr/bin/env bun
// Idempotent sync of the engine roadmap ledger to GitHub issues.
//   bun scripts/issues/sync-issues.ts --dry-run   # print the plan, touch nothing
//   bun scripts/issues/sync-issues.ts             # create/update labels, milestones, issues
// Issues are matched by exact title; bodies, labels and milestones are updated in place.
import { spawnSync } from "node:child_process"
import { AREAS, EXTRA_LABELS, ISSUES, MILESTONES, type Issue } from "./engine-issues"

const DRY = process.argv.includes("--dry-run")
const REPO = "crafter-station/latex0"
const ROADMAP = `https://github.com/${REPO}/blob/main/packages/engine/ROADMAP.md`
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms))

function gh(args: string[]): string {
  if (DRY) return ""
  const p = spawnSync("gh", args, { encoding: "utf8" })
  if (p.status !== 0) throw new Error(`gh ${args.slice(0, 3).join(" ")} failed: ${p.stderr}`)
  return p.stdout.trim()
}

const areaOf = (k: Issue["area"]) => AREAS.find((a) => a.key === k)!

function featureBody(x: Issue, trackingNo: number | undefined): string {
  const a = areaOf(x.area)
  return [
    `## Scope`, x.scope, ``,
    ...(x.ref ? [`## Reference`, x.ref, ``] : []),
    `## Checklist`, ...x.checks.map((c) => `- [ ] ${c}`), ``,
    `## Acceptance`, x.accept, ``,
    `---`,
    `Roadmap: [ROADMAP.md](${ROADMAP}) ${a.section} · Milestone: ${MILESTONES[x.ms].title}` + (trackingNo ? ` · Tracking: #${trackingNo}` : ``),
    `Every PR for this issue adds micro fixtures and must not lower the conformance scorecard.`,
  ].join("\n")
}

function trackingBody(areaKey: Issue["area"], numbers: Map<string, number>): string {
  const a = areaOf(areaKey)
  const lines = [`Tracking issue for **${a.name}** (roadmap ${a.section}). Closing a linked issue ticks it automatically.`, ``]
  MILESTONES.forEach((m, idx) => {
    const items = ISSUES.filter((x) => x.area === areaKey && x.ms === idx)
    if (!items.length) return
    lines.push(`### ${m.title}`)
    for (const x of items) {
      const n = numbers.get(x.title)
      lines.push(n ? `- [ ] #${n}` : `- [ ] ${x.title}`)
    }
    lines.push(``)
  })
  lines.push(`---`, `Full map: [ROADMAP.md](${ROADMAP}). Regenerated by \`scripts/issues/sync-issues.ts\`.`)
  return lines.join("\n")
}

async function main() {
  console.log(`${DRY ? "[dry-run] " : ""}syncing ${ISSUES.length} feature issues + ${AREAS.length} tracking issues to ${REPO}`)

  // 1. labels
  const labels = [...EXTRA_LABELS, ...AREAS.map((a) => ({ label: a.label, color: a.color, description: a.name }))]
  for (const l of labels) {
    gh(["label", "create", l.label, "--color", l.color, "--description", l.description, "--force", "--repo", REPO])
  }
  console.log(`labels: ${labels.length} ensured`)

  // 2. milestones
  const existingMs: { number: number; title: string }[] = DRY ? [] : JSON.parse(gh(["api", `repos/${REPO}/milestones?state=all&per_page=100`]))
  const msNumber = new Map<string, number>()
  for (const m of MILESTONES) {
    const found = existingMs.find((e) => e.title === m.title)
    if (found) { msNumber.set(m.title, found.number); continue }
    if (!DRY) {
      const created = JSON.parse(gh(["api", "-X", "POST", `repos/${REPO}/milestones`, "-f", `title=${m.title}`, "-f", `description=${m.description}`]))
      msNumber.set(m.title, created.number)
      await sleep(1100)
    }
  }
  console.log(`milestones: ${MILESTONES.length} ensured`)

  // 3. existing issues by title
  const existing: { number: number; title: string }[] = DRY ? [] : JSON.parse(gh(["issue", "list", "--repo", REPO, "--state", "all", "--limit", "1000", "--json", "number,title"]))
  const numbers = new Map<string, number>(existing.map((e) => [e.title, e.number]))

  async function upsert(title: string, body: string, labels: string[], milestone?: string): Promise<number | undefined> {
    const n = numbers.get(title)
    const common = ["--repo", REPO, "--body", body, ...(milestone ? ["--milestone", milestone] : [])]
    if (DRY) { console.log(`  ${n ? "update" : "create"}: ${title}  [${labels.join(", ")}]${milestone ? ` (${milestone})` : ""}`); return n }
    if (n) {
      gh(["issue", "edit", String(n), ...common, ...labels.flatMap((l) => ["--add-label", l])])
    } else {
      const url = gh(["issue", "create", "--title", title, ...common, ...labels.flatMap((l) => ["--label", l])])
      const m = url.match(/\/issues\/(\d+)/)
      if (m) numbers.set(title, Number(m[1]))
    }
    await sleep(1100) // stay under GitHub's content-creation secondary rate limit
    return numbers.get(title)
  }

  // 4. tracking issues first (so features can link to them), with provisional bodies
  const trackingTitle = (k: Issue["area"]) => `Tracking: ${areaOf(k).name}`
  for (const a of AREAS) await upsert(trackingTitle(a.key), trackingBody(a.key, numbers), ["engine", "tracking", a.label])

  // 5. feature issues
  for (const x of ISSUES) {
    const a = areaOf(x.area)
    const labels = ["engine", a.label, ...(x.binding ? ["binding"] : []), ...(x.gfi ? ["good first issue"] : [])]
    await upsert(x.title, featureBody(x, numbers.get(trackingTitle(x.area))), labels, MILESTONES[x.ms].title)
  }

  // 6. tracking bodies with real numbers
  for (const a of AREAS) await upsert(trackingTitle(a.key), trackingBody(a.key, numbers), ["engine", "tracking", a.label])

  // summary
  console.log("\nplan summary")
  MILESTONES.forEach((m, idx) => console.log(`  ${m.title}: ${ISSUES.filter((x) => x.ms === idx).length} issues`))
  AREAS.forEach((a) => console.log(`  ${a.label}: ${ISSUES.filter((x) => x.area === a.key).length} issues`))
  console.log(`  binding: ${ISSUES.filter((x) => x.binding).length}, good first issue: ${ISSUES.filter((x) => x.gfi).length}`)
  const dupes = ISSUES.map((x) => x.title).filter((t, i, arr) => arr.indexOf(t) !== i)
  if (dupes.length) throw new Error(`duplicate titles: ${dupes.join(" | ")}`)
}

main().catch((e) => { console.error(e); process.exit(1) })
